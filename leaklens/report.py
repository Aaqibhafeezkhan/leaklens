from __future__ import annotations

import html

PAGE = """<!doctype html><html><head><meta charset="utf-8"><title>@@TITLE@@</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
body{font-family:system-ui,Segoe UI,Arial,sans-serif;background:#0d1117;color:#e6edf3;max-width:900px;margin:40px auto;padding:0 16px}
h1{margin:0 0 4px}h2{margin-top:32px;border-bottom:1px solid #30363d;padding-bottom:6px}
.sub{color:#8b949e}.score{font-size:72px;font-weight:700;color:@@COLOR@@}
.card{background:#161b22;border:1px solid #30363d;border-radius:10px;padding:16px;margin-top:16px}
table{border-collapse:collapse;width:100%;font-size:14px}
th,td{border-bottom:1px solid #30363d;padding:8px;text-align:left;vertical-align:top}th{color:#8b949e}
.kv span{display:inline-block;margin-right:24px}
</style></head><body>
<h1>@@TITLE@@</h1><div class="sub">Generated by LeakLens</div>
<div class="card"><div class="sub">Trust score</div><div class="score">@@SCORE@@/100</div></div>
@@AUDIT@@
<h2>Findings</h2>@@FINDINGS@@
@@ARENA@@
</body></html>"""


def _table(rows):
    if not rows:
        return ""
    heads = list(rows[0])
    h = "".join(f"<th>{html.escape(str(k))}</th>" for k in heads)
    b = "".join("<tr>" + "".join(f"<td>{html.escape(str(r.get(k, '')))}</td>" for k in heads) + "</tr>" for r in rows)
    return f"<table><tr>{h}</tr>{b}</table>"


def render(rep: dict, title: str = "LeakLens report") -> str:
    s = int(rep["trust_score"])
    color = "#2ea043" if s >= 85 else "#d29922" if s >= 60 else "#f85149"
    a = rep.get("audit")
    audit = ""
    if a:
        kv = "".join(f"<span><b>{html.escape(k)}</b> {html.escape(str(a[k]))}</span>"
                     for k in ("rows", "cols", "duplicate_rows", "minority_rate") if k in a)
        audit = f'<div class="card kv">{kv}</div>'
    fnd = _table(rep.get("findings", [])) or '<div class="card">No leakage found.</div>'
    arena = ""
    if rep.get("arena"):
        arena = "<h2>Model arena</h2>" + _table(rep["arena"])
    return (PAGE.replace("@@TITLE@@", html.escape(title)).replace("@@COLOR@@", color)
            .replace("@@SCORE@@", str(s)).replace("@@AUDIT@@", audit)
            .replace("@@FINDINGS@@", fnd).replace("@@ARENA@@", arena))